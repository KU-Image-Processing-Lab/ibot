import torch
import torch.nn as nn
import torch.nn.functional as F

# ネットワークのモジュール化
class Model(nn.Module):
    def __init__(self):
         super().__init__()
        ## ネットワークを定義
        #features
         self.cov1= nn.Conv2d(3,64, kernel_size=3, padding=1)
         self.R1=nn.ReLU()
         self.cov2=nn.Conv2d(64,64, kernel_size=3, padding=1)
         self.R2=nn.ReLU()
         self.Pool1=nn.MaxPool2d(kernel_size=2, stride=2)
         self.cov3=nn.Conv2d(64,128, kernel_size=3, padding=1)
         self.R3=nn.ReLU()
         self.cov4=nn.Conv2d(128,128, kernel_size=3, padding=1)
         self.R4=nn.ReLU()
         self.Pool2=nn.MaxPool2d(kernel_size=2, stride=2)
         self.cov5=nn.Conv2d(128,256, kernel_size=3, padding=1)
         self.R5=nn.ReLU()
         self.cov6=nn.Conv2d(256,256, kernel_size=3, padding=1)
         self.R6=nn.ReLU()
         self.cov7=nn.Conv2d(256,256, kernel_size=3, padding=1)
         self.R7=nn.ReLU()
         self.Pool3=nn.MaxPool2d(kernel_size=2, stride=2)
         self.cov8=nn.Conv2d(256,512, kernel_size=3, padding=1)
         self.R8=nn.ReLU()
         self.cov9=nn.Conv2d(512,512, kernel_size=3, padding=1)
         self.R9=nn.ReLU()
         self.cov10=nn.Conv2d(512,512, kernel_size=3, padding=1)
         self.R10=nn.ReLU()
         self.Pool4=nn.MaxPool2d(kernel_size=2, stride=2)
         self.cov11=nn.Conv2d(512,512, kernel_size=3, padding=1)
         self.R11=nn.ReLU()
         self.cov12=nn.Conv2d(512,512, kernel_size=3, padding=1)
         self.R12=nn.ReLU()
         self.cov13=nn.Conv2d(512,512, kernel_size=3, padding=1)
         self.R13=nn.ReLU()
         self.Pool5=nn.MaxPool2d(kernel_size=2, stride=2)
         self.avgpool = nn.AdaptiveAvgPool2d((7, 7))
         #classifier
         self.liner1=nn.Linear(512 * 7 * 7, 4096)
         self.R14= nn.ReLU(True)
         self.D1=nn.Dropout(p=0.5)
         self.liner2=nn.Linear(4096, 4096)
         self.R15=nn.ReLU(True)
         self.D2=nn.Dropout(p=0.5)
         self.liner3=nn.Linear(4096,2)
    # 順伝搬を定義
    def forward(self, x):
        x=self.cov1(x)
        x=self.R1(x)
        x=self.cov2(x)
        x=self.R2(x)
        x= self.Pool1(x)
        x=self.cov3(x)
        x=self.R3(x)
        x=self.cov4(x)
        x=self.R4(x)
        x=self.Pool2(x)
        x=self.cov5(x)
        x=self.R5(x)
        x=self.cov6(x)
        x=self.R6(x)
        x=self.cov7(x)
        x=self.R7(x)
        x=self.Pool3(x)
        x=self.cov8(x)
        x=self.R8(x)
        x=self.cov9(x)
        x=self.R9(x)
        x=self.cov10(x)
        x=self.R10(x)
        x=self.Pool4(x)
        x=self.cov11(x)
        x=self.R11(x)
        x=self.cov12(x)
        x=self.R12(x)
        x=self.cov13(x)
        x=self.R13(x)
        x=self.avgpool(x)
        x = torch.flatten(x, 1)
#classifier
        x=self.liner1(x)
        x=self.R14(x)
        x=self.D1(x)
        x=self.liner2(x)
        x=self.R15(x)
        x=self.D2(x)
        x=self.liner3(x)
        return x
    
